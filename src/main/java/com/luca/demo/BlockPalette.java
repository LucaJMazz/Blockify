    public static MinecraftBlock findClosest(int r, int g, int b) {
        MinecraftBlock best = null;
        double bestDist = Double.MAX_VALUE;

        for (MinecraftBlock block : BLOCKS) {
            double dist = Math.pow(r - block.r(), 2)
                        + Math.pow(g - block.g(), 2)
                        + Math.pow(b - block.b(), 2);
            if (dist < bestDist) {
                bestDist = dist;
                best = block;
            }
        }
        return best;
    }
